package gov.nih.nci.evs.reportwriter.core.model.evs;

/** The Class EvsSynonym. */
public class EvsSynonym {

  /** The code. */
  private String code;

  /** The label. */
  private String label;

  /** The term name. */
  private String termName;

  /** The term group. */
  private String termGroup;

  /** The term source. */
  private String termSource;

  /** The source code. */
  private String sourceCode;

  /** The sub source name. */
  private String subSourceName;

  /**
   * Gets the code.
   *
   * @return the code
   */
  public String getCode() {
    return code;
  }

  /**
   * Sets the code.
   *
   * @param code the new code
   */
  public void setCode(String code) {
    this.code = code;
  }

  /**
   * Gets the label.
   *
   * @return the label
   */
  public String getLabel() {
    return label;
  }

  /**
   * Sets the label.
   *
   * @param label the new label
   */
  public void setLabel(String label) {
    this.label = label;
  }

  /**
   * Gets the term name.
   *
   * @return the term name
   */
  public String getTermName() {
    return termName;
  }

  /**
   * Sets the term name.
   *
   * @param termName the new term name
   */
  public void setTermName(String termName) {
    this.termName = termName;
  }

  /**
   * Gets the term group.
   *
   * @return the term group
   */
  public String getTermGroup() {
    return termGroup;
  }

  /**
   * Sets the term group.
   *
   * @param termGroup the new term group
   */
  public void setTermGroup(String termGroup) {
    this.termGroup = termGroup;
  }

  /**
   * Gets the term source.
   *
   * @return the term source
   */
  public String getTermSource() {
    return termSource;
  }

  /**
   * Sets the term source.
   *
   * @param termSource the new term source
   */
  public void setTermSource(String termSource) {
    this.termSource = termSource;
  }

  /**
   * Gets the source code.
   *
   * @return the source code
   */
  public String getSourceCode() {
    return sourceCode;
  }

  /**
   * Sets the source code.
   *
   * @param sourceCode the new source code
   */
  public void setSourceCode(String sourceCode) {
    this.sourceCode = sourceCode;
  }

  /**
   * Gets the sub source name.
   *
   * @return the sub source name
   */
  public String getSubSourceName() {
    return subSourceName;
  }

  /**
   * Sets the sub source name.
   *
   * @param subSourceName the new sub source name
   */
  public void setSubSourceName(String subSourceName) {
    this.subSourceName = subSourceName;
  }
}
